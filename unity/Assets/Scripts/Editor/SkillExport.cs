using System.Collections.Generic;
using System.IO;
using System.Text;
using UnityEditor;
using UnityEngine;

/// <summary>
/// Writes the ONE machine-readable record of every composed skill — <c>data/skills.json</c> at the repo root — from
/// the skill assets, and nothing else ever writes it.
///
/// <para><b>Why this exists.</b> The asset already owns every number, and the game reads it live, so the hover card
/// can't drift. The player WIKI and the design DOCS could: both used to be hand-typed prose restating those same
/// numbers, and both fell out of step with the assets more than once — a cooldown said one thing in the game and
/// another on the page, with nobody able to tell which was right. This export closes that by making the wiki and the
/// docs READERS of the assets instead of copies of them.</para>
///
/// <para><b>The words come from <see cref="SkillTooltip"/>, never from here.</b> Every sentence in the export is
/// produced by the same describer the in-game hover card uses, asked for its markdown dialect. That is the whole
/// point: there is exactly one place that decides how a skill is worded, so the wiki literally prints what the player
/// is told. A second describer living in this file would be the drift we are deleting.</para>
///
/// <para><b>Neutral ground on purpose.</b> The file sits at the repo root rather than inside <c>wiki/</c> or
/// <c>docs/</c>, because neither of those owns the other's data — they are both consumers. The wiki gets its own
/// served copy (it fetches relative to its own folder), written here in the same pass and verified by
/// <c>tools/check-skill-data.py</c>, so the copy can never quietly rot.</para>
/// </summary>
public static class SkillExport
{
    // Repo root = two levels up from Application.dataPath (…/unwritten-tempo/unity/Assets).
    static string RepoRoot => Path.GetFullPath(Path.Combine(Application.dataPath, "..", ".."));

    /// <summary>The neutral owner. Hand-editing this is what the whole export exists to make unnecessary.</summary>
    public static string ExportPath => Path.Combine(RepoRoot, "data", "skills.json");

    /// <summary>The wiki's served copy — byte-identical, regenerated from the same pass. The wiki fetches relative to
    /// its own folder, so it cannot reach the neutral file directly without assuming how the site is served.</summary>
    public static string WikiCopyPath => Path.Combine(RepoRoot, "wiki", "content", "skills.generated.json");

    /// <summary>The same data as a markdown table, for the design docs. Markdown cannot show a colour, so this
    /// carries the symbol and the numbers and names the weapon's colour as a hex code.</summary>
    public static string DocsTablePath => Path.Combine(RepoRoot, "data", "skills.md");

    [MenuItem("Tools/unwritten/Skills/Export Skill Data (wiki + docs)")]
    public static void ExportMenu()
    {
        int n = Write();
        Debug.Log($"[Skill Composer] Exported {n} skill(s) to data/skills.json and the wiki's copy.");
        AssetDatabase.Refresh();
    }

    /// <summary>Regenerate both files from the assets on disk. Returns how many skills were written.
    /// Called by the Skill Composer's Save, so composing a skill publishes it everywhere in one action.</summary>
    public static int Write()
    {
        var defs = new List<SkillDef>(Resources.LoadAll<SkillDef>("Skills"));
        defs.Sort((a, b) => string.CompareOrdinal(a != null ? a.id : "", b != null ? b.id : ""));

        var lines = new List<string>(8);
        var json = new StringBuilder(16384);
        json.Append("{\n");
        json.Append("  \"note\": \"GENERATED by the Skill Composer (Tools > unwritten > Skills > Export Skill Data). ");
        json.Append("Do NOT hand-edit: the Skill Composer is the only authorized writer of skill data, and the next ");
        json.Append("save overwrites this file. Every sentence here is produced by the same describer the in-game ");
        json.Append("hover card uses, so the wiki and the docs print exactly what the player is told.\",\n");
        // The weapon colours, ONCE. The colour belongs to the weapon, not to each of its skills, so repeating it on
        // twenty-two rows would be twenty-two copies of one fact. Readers join on a skill's `weapon`.
        // A weapon nobody has painted is simply absent, exactly as WeaponColors reports it — that keeps "unchosen"
        // distinguishable from "deliberately black", which a stand-in colour would erase.
        var colors = WeaponColors.Load();
        json.Append("  \"weaponColors\": {");
        int painted = 0;
        if (colors != null)
            foreach (WeaponType w in System.Enum.GetValues(typeof(WeaponType)))
            {
                var c = colors.Lookup(w);
                if (c == null) continue;
                if (painted > 0) json.Append(',');
                json.Append("\n    \"").Append(w).Append("\": \"#")
                    .Append(ColorUtility.ToHtmlStringRGB(c.Value)).Append('"');
                painted++;
            }
        json.Append(painted > 0 ? "\n  },\n" : "},\n");

        json.Append("  \"skills\": [\n");

        int count = 0;
        for (int i = 0; i < defs.Count; i++)
        {
            var d = defs[i];
            if (d == null) continue;
            if (count > 0) json.Append(",\n");
            count++;

            SkillTooltip.EffectLines(d, SkillTooltip.Dialect.Markdown, lines);

            json.Append("    {\n");
            Field(json, "id", d.id, true);
            Field(json, "name", d.displayName, true);
            // The RAW field, not SkillDef.Symbol: a reader needs to know the difference between "Cs" and "nobody
            // authored one", and Symbol's fallback to the whole display name hides it. Empty = unauthored, and each
            // surface decides what to draw in a space too small for a name.
            Field(json, "symbol", d.symbol, true);
            Field(json, "weapon", d.weaponType.ToString(), true);
            Field(json, "archetype", SkillTooltip.ArchetypeName(d.archetype), true);
            Field(json, "family", d.family.ToString(), true);
            Bool(json, "ultimate", d.IsUltimate);
            Bool(json, "passive", d.IsPassive);
            Bool(json, "published", d.published);
            Field(json, "cost", SkillTooltip.CostLine(d, SkillTooltip.Dialect.Markdown), true);
            Num(json, "manaCost", d.manaCost);
            Num(json, "cooldown", d.cooldown);
            Num(json, "castTime", d.castTime);
            Num(json, "castRange", d.castRange);
            Field(json, "trigger", SkillTooltip.TriggerLine(d, SkillTooltip.Dialect.Markdown), true);
            Field(json, "description", d.description, true);
            // The name a forged weapon carries when this skill is its trademark — empty unless the forge can roll it,
            // the same test the forge uses, so the page names exactly the skills a weapon can be named for.
            Field(json, "trademark", Trademarks.Rollable(d, d.weaponType) ? (d.trademarkName ?? "") : "", true);

            json.Append("      \"effects\": [");
            for (int k = 0; k < lines.Count; k++)
            {
                if (k > 0) json.Append(',');
                json.Append("\n        ").Append(Quote(lines[k]));
            }
            json.Append(lines.Count > 0 ? "\n      ]\n" : "]\n");
            json.Append("    }");
        }

        json.Append("\n  ]\n}\n");
        string text = json.ToString();

        WriteIfChanged(ExportPath, text);
        WriteIfChanged(WikiCopyPath, text);
        WriteIfChanged(DocsTablePath, BuildDocsTable(defs, colors));
        return count;
    }

    // The design docs' copy. Same data, same describer — a table instead of prose, so a doc can point at it rather
    // than restate numbers that then rot. Grouped by weapon because the colour is the weapon's.
    static string BuildDocsTable(List<SkillDef> defs, WeaponColors colors)
    {
        var lines = new List<string>(8);
        var md = new StringBuilder(8192);
        md.Append("# Skills — generated\n\n");
        md.Append("**GENERATED by the Skill Composer. Do not edit — the next save overwrites it.** Every number and\n");
        md.Append("every sentence here comes from the same describer the in-game hover card uses, so this table and\n");
        md.Append("the game can never disagree. Design intent lives in the roster docs; this is what is composed.\n");

        var byWeapon = new Dictionary<WeaponType, List<SkillDef>>();
        for (int i = 0; i < defs.Count; i++)
        {
            if (defs[i] == null) continue;
            if (!byWeapon.TryGetValue(defs[i].weaponType, out var list))
                byWeapon[defs[i].weaponType] = list = new List<SkillDef>();
            list.Add(defs[i]);
        }

        foreach (WeaponType w in System.Enum.GetValues(typeof(WeaponType)))
        {
            if (!byWeapon.TryGetValue(w, out var list)) continue;
            var c = colors != null ? colors.Lookup(w) : null;
            md.Append("\n## ").Append(w == WeaponType.None ? "Not in any weapon's pool" : w.ToString());
            md.Append(c != null ? "  —  colour `#" + ColorUtility.ToHtmlStringRGB(c.Value) + "`" : "  —  *no colour chosen*");
            md.Append("\n\n| Symbol | Skill | Tier | Cost | When | What it does |\n| --- | --- | --- | --- | --- | --- |\n");
            for (int i = 0; i < list.Count; i++)
            {
                var d = list[i];
                SkillTooltip.EffectLines(d, SkillTooltip.Dialect.Markdown, lines);
                string tier = d.IsUltimate ? "**ULT**" : d.IsPassive ? "passive" : "active";
                string when = SkillTooltip.TriggerLine(d, SkillTooltip.Dialect.Markdown);
                md.Append("| ").Append(string.IsNullOrWhiteSpace(d.symbol) ? "—" : "`" + d.symbol + "`")
                  .Append(" | ").Append(d.displayName).Append(d.published ? "" : " *(unpublished)*")
                  .Append(" | ").Append(tier)
                  .Append(" | ").Append(Cell(SkillTooltip.CostLine(d, SkillTooltip.Dialect.Markdown)))
                  .Append(" | ").Append(string.IsNullOrEmpty(when) ? "pressed" : Cell(when))
                  .Append(" | ").Append(Cell(string.Join(" · ", lines.ToArray())))
                  .Append(" |\n");
            }
        }
        return md.ToString();
    }

    // A markdown table cell cannot contain a raw newline or an unescaped pipe.
    static string Cell(string s) =>
        (s ?? "").Replace("|", "\\|").Replace("\r", "").Replace("\n", " ").Trim();

    // Only touch the file when the bytes actually differ, so a save that changed nothing leaves a clean diff.
    static void WriteIfChanged(string path, string text)
    {
        Directory.CreateDirectory(Path.GetDirectoryName(path));
        if (File.Exists(path) && File.ReadAllText(path) == text) return;
        File.WriteAllText(path, text);
    }

    static void Field(StringBuilder j, string key, string value, bool comma)
    {
        j.Append("      \"").Append(key).Append("\": ").Append(Quote(value ?? "")).Append(comma ? ",\n" : "\n");
    }

    static void Bool(StringBuilder j, string key, bool value)
    {
        j.Append("      \"").Append(key).Append("\": ").Append(value ? "true" : "false").Append(",\n");
    }

    static void Num(StringBuilder j, string key, float value)
    {
        j.Append("      \"").Append(key).Append("\": ")
         .Append(value.ToString("0.###", System.Globalization.CultureInfo.InvariantCulture)).Append(",\n");
    }

    static string Quote(string s)
    {
        var q = new StringBuilder(s.Length + 16);
        q.Append('"');
        for (int i = 0; i < s.Length; i++)
        {
            char c = s[i];
            switch (c)
            {
                case '"':  q.Append("\\\""); break;
                case '\\': q.Append("\\\\"); break;
                case '\n': q.Append("\\n");  break;
                case '\r': break;
                case '\t': q.Append("\\t");  break;
                default:
                    if (c < 0x20) q.Append("\\u").Append(((int)c).ToString("x4"));
                    else q.Append(c);
                    break;
            }
        }
        return q.Append('"').ToString();
    }
}
