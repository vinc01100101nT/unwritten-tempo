using System.Collections.Generic;
using UnityEngine;

/// <summary>
/// One registered particle effect: a stable <see cref="id"/> mapped to its prefab plus spawn defaults.
/// The <see cref="id"/> is kebab-cased and category-prefixed (e.g. <c>hit.explosion</c>, <c>aura.buff</c>,
/// <c>slash.charge-blue</c>) so gameplay code spawns an effect by NAME, never by a hardcoded prefab reference.
/// </summary>
[System.Serializable]
public class EffectDef
{
    [Tooltip("Stable id used to spawn this effect, e.g. \"hit.explosion\". Category-prefixed kebab-case.")]
    public string id;
    [Tooltip("The particle prefab to instantiate (pooled).")]
    public GameObject prefab;
    [Tooltip("World scale applied to the spawned instance (multiplies the caller's scale). Tune per effect.")]
    public float scale = 1f;
    [Tooltip("World-space position nudge from the spawn point (e.g. lift a hit off the ground). Tune per effect.")]
    public Vector3 offset = Vector3.zero;
    [Tooltip("Forced lifetime in seconds before auto-return. 0 = automatic (plays for the particle system's " +
             "own duration). Set this to cap a one-shot that contains a looping sub-emitter.")]
    public float lifetime = 0f;
    [Tooltip("GROUND-CIRCLE telegraphs only: the VISIBLE ring's world radius when this effect spawns at its " +
             "authored size (caller scale 1). A cast/aim reticle sizes itself to skillRadius / this, so the drawn " +
             "ring lands exactly on the AoE. Eyeball it ONCE per circle prefab — auto-measuring catches stray sparks, " +
             "not the ring. 0 = not a ground circle (telegraph falls back to raw scale).")]
    public float groundRingRadius = 0f;
}

/// <summary>
/// The authored table of particle effects (Hovl Magic pack et al). One asset lives at
/// <c>Resources/EffectLibrary.asset</c>; <see cref="EffectCatalog"/> loads it once and resolves ids to
/// prefabs. Populate/refresh it with <b>Tools ▸ unwritten ▸ Art ▸ Rebuild Effect Library</b> — that scans
/// the effect prefab folders and generates ids, preserving any per-entry tweaks you've made.
/// </summary>
[CreateAssetMenu(menuName = "unwritten/Effect Library", fileName = "EffectLibrary")]
public class EffectLibrary : ScriptableObject
{
    [Tooltip("Every registered effect. Ids are generated by the builder tool; scale/lifetime are hand-tunable.")]
    public List<EffectDef> effects = new List<EffectDef>();
}
